# Example 1
def add(a, b):
    # Returns sum of two numbers
    return a + b


# Example 2
def square(x):
    # Returns square of number
    return x * x


# Example 3
def is_even(number):
    # Returns True if number is even
    return number % 2 == 0


# Example 4
def get_length(text):
    # Returns length of text
    return len(text)


# Using returned values
print(add(5, 3))
print(square(4))
print(is_even(6))
print(get_length("Python"))